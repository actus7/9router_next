// Generates the manifest of provider brand assets shipped in public/providers.
// Without it the dashboard requests /providers/<id>.png for all ~283 providers and
// ~170 of them 404 on every fresh session. Regenerated on prebuild.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { resolve, dirname } from "node:path";

const EXTENSIONS = ["png", "svg", "webp", "jpg", "jpeg"]; // preference order per id
const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const byId = new Map();
for (const file of readdirSync(resolve(root, "public/providers")).sort()) {
  const match = /^(.+)\.([^.]+)$/.exec(file);
  const rank = match ? EXTENSIONS.indexOf(match[2].toLowerCase()) : -1;
  if (rank < 0) continue;
  const id = match[1].toLowerCase();
  const current = byId.get(id);
  if (!current || rank < current.rank) byId.set(id, { file, rank });
}

const entries = [...byId.entries()].sort(([a], [b]) => (a < b ? -1 : 1));
const target = resolve(root, "src/shared/constants/providerIconFiles.ts");
const contents = `// GENERATED by scripts/gen-provider-icons.mjs — do not edit by hand.
// Provider id -> file in public/providers. Ids absent here render their text fallback.
export const PROVIDER_ICON_FILES: Readonly<Record<string, string>> = {
${entries.map(([id, { file }]) => `  "${id}": "${file}",`).join("\n")}
};
`;

const current = (() => { try { return readFileSync(target, "utf8"); } catch { return ""; } })();
if (current !== contents) writeFileSync(target, contents);
console.log(`Provider icon manifest: ${entries.length} assets.`);
